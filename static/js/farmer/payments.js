/**
 * SHREE MILK BANK — Farmer: Payments (history + status)
 * Loads the authenticated farmer's own payments from
 * GET /api/farmer/me/payments (server-scoped to the farmer).
 */
let _paymentsPage = 1;
const PAY_PER_PAGE = 20;

function _payParams() {
  return {
    page: _paymentsPage,
    per_page: PAY_PER_PAGE,
    status: document.getElementById('filter-status')?.value || '',
  };
}

function _payStatusBadge(status) {
  const map = { PAID: 'tag-green', APPROVED: 'tag-blue', PENDING: 'tag-gold' };
  return `<span class="tag ${map[status] || 'tag-neutral'}" style="font-size:10px;">${status ? status.charAt(0) + status.slice(1).toLowerCase() : '—'}</span>`;
}

function _period(p) {
  if (!p) return '—';
  const from = p.periodStart ? fmtDate(p.periodStart) : '';
  const to = p.periodEnd ? fmtDate(p.periodEnd) : '';
  return from && to ? `${from} – ${to}` : (from || to || '—');
}

async function loadFarmerPayments() {
  const body = document.getElementById('payments-body');
  if (body) body.innerHTML = '<tr><td colspan="8" class="text-center" style="padding:var(--space-4);color:var(--ink-muted);font-size:var(--text-sm);">Loading payments…</td></tr>';

  try {
    const data = await API.getMyPayments(_payParams());
    const payments = data.payments || [];
    const summary = data.summary || {};

    const cards = {
      'ph-paid-amount': fmtINR(summary.paidAmount),
      'ph-pending-amount': fmtINR(summary.pendingAmount),
      'ph-paid-count': `${summary.paidCount || 0}`,
      'ph-pending-count': `${summary.pendingCount || 0}`,
    };
    Object.entries(cards).forEach(([id, v]) => {
      const el = document.getElementById(id);
      if (el) el.innerHTML = v;
    });

    const totalEl = document.getElementById('payments-total');
    if (totalEl) totalEl.textContent = `${data.total || 0} payment(s)`;

    const pager = document.getElementById('payments-pager-info');
    if (pager) {
      const from = data.total === 0 ? 0 : ((data.page - 1) * (data.perPage || PAY_PER_PAGE)) + 1;
      const to = Math.min((data.page || 1) * (data.perPage || PAY_PER_PAGE), data.total || 0);
      pager.textContent = `Showing ${from}-${to} of ${data.total || 0} entries`;
    }
    const prev = document.getElementById('payments-prev');
    const next = document.getElementById('payments-next');
    if (prev) prev.disabled = !(data.page && data.page > 1);
    if (next) next.disabled = !(data.page && data.pages && data.page < data.pages);

    if (!payments.length) {
      body.innerHTML = '<tr><td colspan="8" class="text-center" style="padding:var(--space-6);"><div class="empty-icon" style="margin:0 auto var(--space-3);"><i data-lucide="wallet" style="width:36px;height:36px;"></i></div><p style="color:var(--ink-muted);font-size:var(--text-sm);">No payment records found.</p><p style="color:var(--ink-muted);font-size:var(--text-xs);margin-top:var(--space-1);">Payments are generated by the head office from your milk collections.</p></td></tr>';
    } else {
      const isStatusPage = !document.getElementById('filter-status');
      body.innerHTML = payments.map(p => `
        <tr>
          ${isStatusPage ? '' : `<td><span class="font-mono">${p.payCode || '—'}</span></td>`}
          <td>${_period(p)}</td>
          <td>${fmtNum(p.totalQuantity, 2)} L</td>
          ${isStatusPage ? '' : `<td>${p.collectionCount || 0}</td>`}
          <td style="font-weight:600;">${fmtINR(p.totalAmount)}</td>
          <td>${_payStatusBadge(p.status)}</td>
          <td>${p.reference ? '<span class="font-mono" style="font-size:var(--text-xs);">' + p.reference + '</span>' : '—'}</td>
          <td>${p.paidAt ? fmtDate(p.paidAt) : '—'}</td>
        </tr>`).join('');
    }
    if (window.lucide) lucide.createIcons();
  } catch (err) {
    console.warn('Failed to load payments:', err);
    if (body) body.innerHTML = `<tr><td colspan="8" class="text-center" style="padding:var(--space-5);">
      <p style="color:var(--ink-muted);font-size:var(--text-sm);">Unable to load payments. Try again.</p>
      <button class="btn btn-sm btn-ghost" style="margin-top:var(--space-2);" onclick="window.refreshFarmerPayments && refreshFarmerPayments()">Try Again</button>
    </td></tr>`;
  }
}

window.refreshFarmerPayments = function () {
  _paymentsPage = 1;
  loadFarmerPayments();
};

window.pageFarmerPayments = function (delta) {
  _paymentsPage = Math.max(1, _paymentsPage + delta);
  loadFarmerPayments();
};

window.initFarmerPayments = function () {
  const statusFilter = document.getElementById('filter-status');
  if (statusFilter) statusFilter.addEventListener('change', () => { _paymentsPage = 1; loadFarmerPayments(); });
  loadFarmerPayments();
};
